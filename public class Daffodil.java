public class Daffodil
{
    // An example method
    public void printMessage() {
        System.out.println("Hello, Daffodil!");
    }
    
    public static void main(String[] args) {
        
        // Create an instance of the class
        // containing the method
        Daffodil obj = new Daffodil ();
        
        // Calling the method
        obj.printMessage(); 
    }
}
